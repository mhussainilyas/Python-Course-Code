# ================
#   Mutable List
# ================

fruits = [ "Apple", "Banana", "Mango" ]
print(fruits)

fruits[1] = "Orange"
print(fruits)

# ======================
#   Mutable Dictionary
# ======================

student = { "name": "Hussain", "age": 20 }
print(student)

student["age"] = 21
print(student)

# ===============
#   Mutable Set
# ===============

skills = { "Python", "Development" }
print(skills)

skills.add("AI")
print(skills)