# ==================================
#   Primitive Data Types in Python
# ==================================

name = "Hussain"           # str
age = 21                   # int
cgpa = 3.47                # float
num = 2 + 3j               # complex
is_student = True          # bool
result = None              # NoneType

print(type(name))
print(type(age))
print(type(cgpa))
print(type(num))
print(type(is_student))
print(type(result))

# ======================================
#   Non Primitive Data Types in Python
# ======================================

fruits = ["Apple", "Mango"]               # list
colors = ("Red", "Blue")                  # tuple
numbers = {1, 2, 3}                       # set
student = {"name": "Hussain", "age": 21}  # dict

print(type(fruits))
print(type(colors))
print(type(numbers))
print(type(student))