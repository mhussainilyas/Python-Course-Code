my_tuple = (10, 20, 30, 40)

# ===========
#   Packing
# ===========

my_tuple_1 = 10, 20, 30, 40

print(my_tuple_1, type(my_tuple_1))

# ==============
#   Un-Packing
# ==============

val_1, val_2, val_3, val_4 = 10, 20, 30, 40

print(val_1, type(val_1))
print(val_2, type(val_2))
print(val_3, type(val_3))
print(val_4, type(val_4))
