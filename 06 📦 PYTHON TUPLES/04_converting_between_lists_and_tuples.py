# ============================
#   Tuple to list conversion
# ============================

my_tuple = (595, "HSN", True, 3.47)
my_list = list(my_tuple)
print(my_list)

# ============================
#   list to Tuple conversion
# ============================

my_list = [595, "HSN", True, 3.47]
my_tuple = tuple(my_list)
print(my_tuple)
