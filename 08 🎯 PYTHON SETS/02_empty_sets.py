# ================================================
#   This is NOT a set — it's an empty dictionary
# ================================================

empty_braces = {}
print(f"Type of {{}}: {type(empty_braces)}") # Output: <class 'dict'>

# ========================
#   This IS an empty set
# ========================

empty_set_func = set()
print(f"Type of set(): {type(empty_set_func)}") # Output: <class 'set'>
